// requirements.txt / environment.yaml for the packages in this Python session,
// so a project can be set up again on a normal machine.

export const ENVIRONMENT_FILES = ["requirements.txt", "environment.yaml"] as const;
export type EnvironmentFile = (typeof ENVIRONMENT_FILES)[number];

/** Shipped with Pyodide and also on conda-forge; the rest are pip packages. */
const CONDA = new Set(["numpy", "scipy", "matplotlib", "sympy", "pandas"]);

const normalize = (name: string) => name.toLowerCase().replace(/[_.]+/g, "-");

/** Distribution names with versions, minus the interpreter, sorted. */
function entries(packages: Record<string, string>) {
  return Object.entries(packages)
    .filter(([name]) => name !== "python")
    .map(([name, version]) => [normalize(name), version] as const)
    .sort(([a], [b]) => a.localeCompare(b));
}

const header = (python?: string) =>
  `# Generated by QisPlay${python ? ` (Python ${python})` : ""}\n`;

/** One pinned `name==version` per line. */
export function requirementsTxt(packages: Record<string, string>) {
  const lines = entries(packages).map(([name, version]) => `${name}==${version}`);
  return `${header(packages.python)}${lines.join("\n")}\n`;
}

/** conda `major.minor` pin: matches any patch release, which conda-forge's builds may differ in. */
const minor = (version: string) => version.split(".").slice(0, 2).join(".");

const envName = (project: string) =>
  normalize(project).replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "") || "qisplay";

/** A conda environment: scientific packages from conda-forge, the rest through pip. */
export function environmentYaml(packages: Record<string, string>, project: string) {
  const all = entries(packages);
  const conda = all.filter(([name]) => CONDA.has(name));
  const pip = all.filter(([name]) => !CONDA.has(name));
  const lines = [
    `name: ${envName(project)}`,
    "channels:",
    "  - conda-forge",
    "dependencies:",
    `  - python=${minor(packages.python ?? "3.14")}`,
    ...conda.map(([name, version]) => `  - ${name}=${minor(version)}`),
    ...(pip.length ? ["  - pip", "  - pip:", ...pip.map(([name, version]) => `      - ${name}==${version}`)] : []),
  ];
  return `${header(packages.python)}${lines.join("\n")}\n`;
}
